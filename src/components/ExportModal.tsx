import React, { useState } from 'react';
import { X, Copy, Check, FileText, Download } from 'lucide-react';
import { IncidentSubmission, InvestigationPlan, IncidentMemory } from '../types';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  incident: IncidentSubmission | null;
  plan: InvestigationPlan | null;
  evidence: IncidentMemory[];
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  incident,
  plan,
  evidence
}) => {
  if (!isOpen || !plan) return null;

  const [copied, setCopied] = useState(false);

  const markdownContent = `# [INCIDENT INVESTIGATION PLAN] ${incident?.title || 'Active Incident'}
**Service:** ${incident?.service || 'N/A'}  
**Severity:** ${incident?.severity || 'SEV2'}  
**Generated By:** RecallOps Advisory Engine (with Hindsight Persistent Memory)  
**Confidence:** ${plan.confidenceScore}%  
**Date:** ${new Date().toISOString()}  

---

## 1. Executive Summary
${plan.summary}

---

## 2. Retrieved Historical Evidence
${evidence.map(e => `- **[${e.evidenceCode}] ${e.id}** (${e.service}): ${e.title}
  - *Historical Fix:* ${e.successfulFix}
  - *Avoided Mistake:* ${e.failedActions.join('; ')}`).join('\n\n')}

---

## 3. Investigated Hypotheses (Requires Verification)
${plan.hypotheses.map(h => `${h.rank}. **[${h.confidence} Confidence]** ${h.title}
   - ${h.description} ${h.evidenceReference ? `(Ref: [${h.evidenceReference}])` : ''}`).join('\n')}

---

## 4. Safe Read-Only Diagnostic Checks (DO FIRST)
\`\`\`bash
${plan.readOnlyChecks.map(c => `# Step ${c.step}: ${c.name}
# Target: ${c.expectedObservation}
${c.command}
`).join('\n')}
\`\`\`

---

## 5. ⚠️ INEFFECTIVE / DANGEROUS ACTIONS TO AVOID
${plan.actionsToAvoid.map(a => `- **DO NOT:** ${a.action}
  - *Reason:* ${a.reason} [Ref ${a.citedEvidence}]`).join('\n')}

---

## 6. Recommended Remediations
${plan.recommendedRemediations.map(r => `Priority ${r.priority}: **${r.action}**
- *Historical Rationale:* ${r.rationale}
- *Verification Step:* ${r.verificationStep}`).join('\n\n')}
`;

  const handleCopy = () => {
    navigator.clipboard.writeText(markdownContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const dataStr = "data:text/markdown;charset=utf-8," + encodeURIComponent(markdownContent);
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute("href", dataStr);
    downloadAnchor.setAttribute("download", `recallops-plan-${incident?.service || 'incident'}.md`);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/75 backdrop-blur-sm animate-fadeIn">
      <div 
        className="bg-[#0f172a] border border-slate-700 rounded-2xl w-full max-w-3xl max-h-[90vh] overflow-y-auto shadow-2xl flex flex-col"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="p-5 border-b border-slate-800 bg-slate-900/80 flex items-center justify-between sticky top-0 z-10">
          <div className="flex items-center gap-2.5">
            <FileText className="w-5 h-5 text-cyan-400" />
            <h3 className="text-sm font-semibold text-white">Export Markdown Investigation Report</h3>
          </div>
          <button
            onClick={onClose}
            className="w-8 h-8 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 flex items-center justify-center transition-colors"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        <div className="p-6 space-y-4">
          <p className="text-xs text-slate-400">
            Copy or download this battle-tested markdown report to paste directly into PagerDuty, Slack war-rooms, or incident postmortems.
          </p>

          <pre className="p-4 bg-slate-950 border border-slate-800 rounded-xl text-xs font-mono text-cyan-200/90 whitespace-pre-wrap max-h-96 overflow-y-auto leading-relaxed">
            {markdownContent}
          </pre>
        </div>

        <div className="p-4 border-t border-slate-800 bg-slate-900/80 flex items-center justify-between">
          <button
            onClick={handleDownload}
            className="px-4 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-medium transition-colors flex items-center gap-1.5"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download .md</span>
          </button>

          <div className="flex items-center gap-2">
            <button
              onClick={onClose}
              className="px-4 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs font-medium"
            >
              Close
            </button>
            <button
              onClick={handleCopy}
              className="px-4 py-2 rounded-xl bg-cyan-500 hover:bg-cyan-400 text-slate-950 font-semibold text-xs transition-colors flex items-center gap-1.5"
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5 text-slate-950" />
                  <span>Copied to Clipboard!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5 text-slate-950" />
                  <span>Copy Markdown</span>
                </>
              )}
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
